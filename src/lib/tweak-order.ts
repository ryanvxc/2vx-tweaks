const POSITION = new Map(
  Object.values(KNOWN_FIRST).flatMap((ids) => ids.map((id, i) => [id, i] as const)),
);

const RISK_ORDER: Record<RiskLevel, number> = { low: 0, moderate: 1, high: 2 };
const IMPACT_ORDER: Record<Impact, number> = { low: 0, medium: 1, high: 2 };
const EVIDENCE_ORDER: Record<Evidence, number> = { documented: 0, observed: 1, community: 2 };

type Ranked = Pick<TweakMeta, "id" | "name" | "risk" | "impact" | "evidence" | "recommended">;

/** Past the known ones: anything that can bite goes last, as EXM's Advanced scripts do. */
function leastRiskFirst(a: Ranked, b: Ranked) {
  return (
    RISK_ORDER[a.risk] - RISK_ORDER[b.risk] ||
    Number(b.recommended) - Number(a.recommended) ||
    IMPACT_ORDER[b.impact] - IMPACT_ORDER[a.impact] ||
    EVIDENCE_ORDER[a.evidence] - EVIDENCE_ORDER[b.evidence] ||
    a.name.localeCompare(b.name)
  );
}

/** The default order on every tab: the best-known tweaks first. */
export function mostUsefulFirst(a: Ranked, b: Ranked) {
  const [first, second] = [POSITION.get(a.id), POSITION.get(b.id)];
  if (first !== undefined && second !== undefined) return first - second;
  if (first !== undefined) return -1;
  if (second !== undefined) return 1;
  return leastRiskFirst(a, b);
}
